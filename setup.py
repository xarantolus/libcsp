"""setuptools build for the libcsp Python binding (`libcsp_py3`).

Replaces the upstream waf build for Python-only consumers: lets `pip` /
`uv pip install` consume the source tree directly with no waf round-trip.

Mirrors waf's POSIX + socketcan default. CSP_HAVE_LIBSOCKETCAN is enabled
unconditionally — `apt install libsocketcan-dev` is a prerequisite.
"""
from __future__ import annotations

import glob
from pathlib import Path

from setuptools import Extension, setup

ROOT = Path(__file__).parent

# Generate csp_autoconfig.h into a build-private include dir instead of
# committing it under include/csp/. waf normally writes it to
# include/csp/csp_autoconfig.h at configure time, so dropping a static
# copy there would silently shadow waf-generated values for any user who
# runs waf afterwards. Putting it in build/setuptools-include/ keeps the
# two build systems out of each other's way.
_AUTOCONFIG = """\
/* Generated by setup.py — do not commit. Pinned to the configuration the
   Python binding needs: POSIX host, socketcan driver, no ZMQ/USART/RDP/
   HMAC/XTEA, info-level logging. */
#ifndef LIBCSP_AUTOCONFIG_H
#define LIBCSP_AUTOCONFIG_H

#define CSP_POSIX                 1
#define CSP_FREERTOS              0
#define CSP_WINDOWS               0
#define CSP_MACOSX                0

#define CSP_HAVE_LIBSOCKETCAN     1
#define CSP_HAVE_LIBZMQ           0
#define CSP_HAVE_USART            0

#define CSP_DEBUG                 1
#define CSP_DEBUG_TIMESTAMP       0

#define CSP_USE_RDP               0
#define CSP_USE_RDP_FAST_CLOSE    0
#define CSP_USE_CRC32             1
#define CSP_USE_HMAC              0
#define CSP_USE_XTEA              0
#define CSP_USE_PROMISC           0
#define CSP_USE_QOS               0
#define CSP_USE_DEDUP             0
#define CSP_USE_EXTERNAL_DEBUG    0

#define CSP_LOG_LEVEL_DEBUG       0
#define CSP_LOG_LEVEL_INFO        1
#define CSP_LOG_LEVEL_WARN        1
#define CSP_LOG_LEVEL_ERROR       1

#define CSP_LITTLE_ENDIAN         1
#define CSP_BIG_ENDIAN            0

#define LIBCSP_VERSION            "1.6-xarantolus"

#endif /* LIBCSP_AUTOCONFIG_H */
"""

_GEN_INCLUDE = ROOT / "build" / "setuptools-include"
_autoconfig_dir = _GEN_INCLUDE / "csp"
_autoconfig_dir.mkdir(parents=True, exist_ok=True)
(_autoconfig_dir / "csp_autoconfig.h").write_text(_AUTOCONFIG)

_globs = [
    "src/*.c",
    "src/transport/**/*.c",
    "src/crypto/**/*.c",
    "src/interfaces/**/*.c",
    "src/arch/*.c",
    "src/arch/posix/**/*.c",
]
# Exclude interfaces whose runtime deps we don't ship: ZMQ requires libzmq;
# I2C requires the platform driver. Keep csp_if_can / kiss / lo.
_exclude = {"src/interfaces/csp_if_zmqhub.c", "src/interfaces/csp_if_i2c.c"}

sources: list[str] = []
for pattern in _globs:
    for path in sorted(glob.glob(pattern, recursive=True, root_dir=ROOT)):
        if path not in _exclude:
            sources.append(path)

# Single rtable backend — matches waf's `--with-rtable=cidr` default.
sources.append("src/rtable/csp_rtable.c")
sources.append("src/rtable/csp_rtable_cidr.c")

# Linux socketcan driver.
sources.append("src/drivers/can/can_socketcan.c")

# The Python binding itself.
sources.append("src/bindings/python/pycsp.c")

ext = Extension(
    name="libcsp_py3",
    sources=sources,
    include_dirs=[
        str(_GEN_INCLUDE),  # ahead of include/ so our autoconfig wins
        "include",
    ],
    libraries=["socketcan", "pthread"],
    define_macros=[
        # Mirrored in the generated csp_autoconfig.h above; we set them here
        # too so build flags don't drift between the two locations.
        ("CSP_POSIX", "1"),
        ("CSP_HAVE_LIBSOCKETCAN", "1"),
    ],
    extra_compile_args=["-std=gnu11", "-Wno-unused-parameter"],
)

setup(
    name="libcsp_py3",
    version="1.6.0",
    description="Python bindings for libcsp.",
    ext_modules=[ext],
    py_modules=[],
)
