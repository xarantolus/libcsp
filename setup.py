"""setuptools build for the libcsp Python binding (`libcsp_py3`) on v2.1.

Upstream libcsp ships a CMake target for the binding (`libcsp_py3` via
`-DCSP_ENABLE_PYTHON3_BINDINGS=ON -DCSP_USE_RTABLE=ON`). Driving CMake
from a wheel build adds a toolchain hop Python consumers shouldn't need,
so this file enumerates the same sources directly as a setuptools
Extension.

Assumes POSIX host with socketcan available (`apt install
libsocketcan-dev`); mirrors the defaults exercised by upstream's
build-test-python CI.
"""
from __future__ import annotations

from pathlib import Path

from setuptools import Extension, setup

ROOT = Path(__file__).parent

# Upstream generates csp/autoconfig.h from csp_autoconfig.h.in via
# configure_file(). Reproduce the same defines into a build-private include
# dir so the staged header is never committed alongside the source tree.
_AUTOCONFIG = """\
/* Generated by setup.py — do not commit. Pinned to the configuration the
   Python binding uses: POSIX host, socketcan, HMAC + RDP + promisc +
   rtable on, ZMQ off. Mirrors csp_autoconfig.h.in with the options fed to
   upstream CMake. */
#ifndef CSP_AUTOCONFIG_H
#define CSP_AUTOCONFIG_H

#define CSP_POSIX                    1
#define CSP_ZEPHYR                   0
#define CSP_FREERTOS                 0

#define CSP_HAVE_STDIO               1
#define CSP_ENABLE_CSP_PRINT         1
#define CSP_PRINT_STDIO              1

#define CSP_REPRODUCIBLE_BUILDS      0

#define CSP_QFIFO_LEN                15
#define CSP_PORT_MAX_BIND            16
#define CSP_CONN_RXQUEUE_LEN         16
#define CSP_CONN_MAX                 8
#define CSP_BUFFER_SIZE              256
#define CSP_BUFFER_COUNT             15
#define CSP_RDP_MAX_WINDOW           5
#define CSP_RTABLE_SIZE              10

#define CSP_USE_RDP                  1
#define CSP_USE_HMAC                 1
#define CSP_USE_PROMISC              1
#define CSP_USE_RTABLE               1
#define CSP_BUFFER_ZERO_CLEAR        1

#define CSP_HAVE_LIBSOCKETCAN        1
#define CSP_HAVE_LIBZMQ              0

#define CSP_FIXUP_V1_ZMQ_LITTLE_ENDIAN 1

#endif
"""

_gen_include = ROOT / "build" / "setuptools-include"
(_gen_include / "csp").mkdir(parents=True, exist_ok=True)
(_gen_include / "csp" / "autoconfig.h").write_text(_AUTOCONFIG)


# Source list — mirrors upstream's src/CMakeLists.txt with our Kconfig
# choices. Grouped the same way so drift shows up in review.
sources = [
    # Core (unconditional in upstream CMake).
    "src/csp_bridge.c",
    "src/csp_buffer.c",
    "src/csp_conn.c",
    "src/csp_crc32.c",
    "src/csp_debug.c",
    "src/csp_dedup.c",
    "src/csp_id.c",
    "src/csp_iflist.c",
    "src/csp_init.c",
    "src/csp_io.c",
    "src/csp_port.c",
    "src/csp_qfifo.c",
    "src/csp_route.c",
    "src/csp_service_handler.c",
    # CMP request handlers, split out of csp_service_handler.c upstream
    "src/cmp/csp_cmp_clock.c",
    "src/cmp/csp_cmp_dispatch.c",
    "src/cmp/csp_cmp_ident.c",
    "src/cmp/csp_cmp_if_stats.c",
    "src/cmp/csp_cmp_mem.c",
    "src/cmp/csp_cmp_peek_poke.c",
    "src/cmp/csp_cmp_route.c",
    "src/csp_services.c",
    "src/csp_sfp.c",
    # CSP_ENABLE_CSP_PRINT.
    "src/csp_hex_dump.c",
    # CSP_USE_PROMISC.
    "src/csp_promisc.c",
    # CSP_USE_RDP (required by pycsp bindings API).
    "src/csp_rdp.c",
    "src/csp_rdp_queue.c",
    # CSP_USE_RTABLE (required by pycsp bindings per upstream docs).
    "src/csp_rtable_cidr.c",
    "src/csp_rtable_stdio.c",
    # POSIX arch.
    "src/arch/posix/csp_clock.c",
    "src/arch/posix/csp_queue.c",
    "src/arch/posix/csp_semaphore.c",
    "src/arch/posix/csp_system.c",
    "src/arch/posix/csp_time.c",
    "src/arch/posix/pthread_queue.c",
    # Crypto (CSP_USE_HMAC).
    "src/crypto/csp_hmac.c",
    "src/crypto/csp_sha1.c",
    # Interfaces — skip i2c (platform driver), zmqhub (needs libzmq),
    # tun (needs crypto hooks at runtime).
    "src/interfaces/csp_if_lo.c",
    "src/interfaces/csp_if_can.c",
    "src/interfaces/csp_if_can_pbuf.c",
    "src/interfaces/csp_if_kiss.c",
    "src/interfaces/csp_if_udp.c",
    "src/interfaces/csp_if_eth.c",
    "src/interfaces/csp_if_eth_pbuf.c",
    # Drivers.
    "src/drivers/can/can_socketcan.c",
    "src/drivers/usart/usart_kiss.c",
    "src/drivers/usart/usart_linux.c",
    "src/drivers/eth/eth_linux.c",
    # The Python binding itself.
    "src/bindings/python/pycsp.c",
]

ext = Extension(
    name="libcsp_py3",
    sources=sources,
    include_dirs=[
        str(_gen_include),  # staged autoconfig.h, found via #include "csp/autoconfig.h"
        "include",
        "src",  # internal headers (csp_macro.h, csp_conn.h, csp_rdp*.h, ...) live next to the sources
    ],
    libraries=["socketcan", "pthread"],
    define_macros=[
        # csp_rdp.c needs `_DEFAULT_SOURCE` for endian.h; upstream sets it
        # per-file via set_source_files_properties. Setting it globally is
        # equivalent and avoids a custom build_ext.
        ("_DEFAULT_SOURCE", "1"),
    ],
    extra_compile_args=["-std=gnu11", "-Wno-unused-parameter"],
)

# PEP 561 stubs-only package — ships libcsp_py3-stubs/__init__.pyi next
# to the extension so language servers can resolve symbols. PEP 561
# treats the `-stubs` directory suffix as the marker; no py.typed file
# is needed. Hand-written (real arg names, NewType capsules); a drift
# test in the consumer repo asserts dir(libcsp_py3) stays in sync with
# the stub's exports.
setup(
    ext_modules=[ext],
    packages=["libcsp_py3-stubs"],
    package_data={"libcsp_py3-stubs": ["__init__.pyi"]},
)
